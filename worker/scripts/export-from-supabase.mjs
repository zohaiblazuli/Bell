#!/usr/bin/env node
// One-time data migration: read the community content tables out of Supabase via
// PostgREST and emit a D1-ready SQL file of INSERTs. Fresh-keys migration, so it
// deliberately SKIPS community_votes / community_events / community_admin_ip_events
// (hashed/encrypted with the old key), rate limits (ephemeral), scan tables
// (scanner out of scope) and admin_users (re-seeded via seed-admin.mjs).
//
//   SUPABASE_URL=https://<ref>.supabase.co \
//   SUPABASE_SERVICE_ROLE_KEY=<key> \
//   [ADMIN_USER_ID=<new-admin-uuid>] \
//   node scripts/export-from-supabase.mjs
//
// Output: worker/seed/seed-data.sql  ->  wrangler d1 execute bell-community --remote --file seed/seed-data.sql
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const SUPABASE_URL = process.env.SUPABASE_URL;
const KEY = process.env.SUPABASE_SERVICE_ROLE_KEY;
const ADMIN_USER_ID = process.env.ADMIN_USER_ID; // optional: re-attribute created_by/actor_id
if (!SUPABASE_URL || !KEY) {
  console.error('Set SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY.');
  process.exit(1);
}

// Ordered for FK safety (parents before children). id/identity columns omitted so
// D1 AUTOINCREMENT reassigns them. Keys are the D1 column names (they match PG).
const TABLES = [
  { name: 'community_resources', remapUser: 'created_by' },
  { name: 'community_resource_versions', remapUser: 'created_by' },
  { name: 'community_daily_stats' },
  { name: 'community_admin_audit', omit: ['id'], remapUser: 'actor_id' },
];

function sqlValue(value) {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'boolean') return value ? '1' : '0';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'object') return `'${JSON.stringify(value).replace(/'/g, "''")}'`;
  return `'${String(value).replace(/'/g, "''")}'`;
}

async function fetchTable(name) {
  const res = await fetch(`${SUPABASE_URL}/rest/v1/${name}?select=*`, {
    headers: { apikey: KEY, authorization: `Bearer ${KEY}` },
  });
  if (!res.ok) throw new Error(`${name}: HTTP ${res.status} ${await res.text()}`);
  return res.json();
}

const lines = [
  '-- Generated by export-from-supabase.mjs. Apply after 0001_init.',
  'PRAGMA foreign_keys = OFF;',
  'BEGIN TRANSACTION;',
];

for (const spec of TABLES) {
  const rows = await fetchTable(spec.name);
  for (const row of rows) {
    if (spec.omit) for (const col of spec.omit) delete row[col];
    if (ADMIN_USER_ID && spec.remapUser && row[spec.remapUser]) row[spec.remapUser] = ADMIN_USER_ID;
    const cols = Object.keys(row);
    const vals = cols.map((c) => sqlValue(row[c]));
    lines.push(`INSERT OR IGNORE INTO ${spec.name} (${cols.join(', ')}) VALUES (${vals.join(', ')});`);
  }
  console.error(`${spec.name}: ${rows.length} rows`);
}

lines.push('COMMIT;', "INSERT INTO community_resources_fts(community_resources_fts) VALUES('rebuild');", '');

const outPath = fileURLToPath(new URL('../seed/seed-data.sql', import.meta.url));
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, lines.join('\n'));
console.error(`\nWrote ${outPath}`);
console.error('Apply with: wrangler d1 execute bell-community --remote --file seed/seed-data.sql');
